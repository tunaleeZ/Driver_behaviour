# ---------------------------------------------------------------------------
# Directory tree to create
# ---------------------------------------------------------------------------

def _dirs_to_create(root: Path) -> list[Path]:
    """Return list of directories that init_dataset should create."""
    labels = ["drinking", "drowsy", "normal", "phone", "sleepy"]
    dirs = [
        root / "annotations",
        root / "features",
        root / "features" / "landmarks",
        root / "processed",
        root / "processed" / "frames",
        root / "raw",
        root / "raw" / "public",
        root / "scripts",
    ]
    for label in labels:
        dirs.append(root / "segments" / label)
    return dirs


def _gitkeep_dirs(root: Path) -> list[Path]:
    """Return directories that need a .gitkeep file."""
    return [
        root / "features",
        root / "features" / "landmarks",
        root / "processed",
        root / "processed" / "frames",
        root / "raw" / "public",
    ]


# ---------------------------------------------------------------------------
# Main logic
# ---------------------------------------------------------------------------

def init_dataset(root: Path, dry_run: bool = False, overwrite: bool = False) -> None:
    """Create the dataset directory tree.

    Parameters
    ----------
    root:
        Root directory to initialise.
    dry_run:
        If True, only print what would be done without writing anything.
    overwrite:
        If True, overwrite existing text files (README, .gitignore).
    """
    prefix = "[DRY-RUN] " if dry_run else ""

    # 1. Create directories
    for d in _dirs_to_create(root):
        if not d.exists():
            logger.info("%sCreating directory: %s", prefix, d)
            if not dry_run:
                d.mkdir(parents=True, exist_ok=True)
        else:
            logger.debug("Directory already exists: %s", d)

    # 2. Create .gitkeep files
    for d in _gitkeep_dirs(root):
        gk = d / ".gitkeep"
        if not gk.exists():
            logger.info("%sCreating .gitkeep: %s", prefix, gk)
            if not dry_run:
                gk.touch()

    # 3. Create .gitignore
    _write_text_file(
        root / ".gitignore",
        _DATASET_GITIGNORE,
        dry_run=dry_run,
        overwrite=overwrite,
        label=".gitignore",
    )

    # 4. Create README_Driver_Behavior_Dataset.md
    _write_text_file(
        root / "README_Driver_Behavior_Dataset.md",
        _DATASET_README,
        dry_run=dry_run,
        overwrite=overwrite,
        label="README_Driver_Behavior_Dataset.md",
    )

    logger.info("%sDataset initialised at: %s", prefix, root)


def _write_text_file(
    path: Path,
    content: str,
    dry_run: bool,
    overwrite: bool,
    label: str,
) -> None:
    """Write a text file, respecting idempotency and dry-run settings."""
    prefix = "[DRY-RUN] " if dry_run else ""
    if path.exists() and not overwrite:
        logger.debug("File already exists (skip): %s", path)
        return
    action = "Overwriting" if path.exists() else "Creating"
    logger.info("%s%s: %s", prefix, action, path)
    if not dry_run:
        path.write_text(content, encoding="utf-8")


# ---------------------------------------------------------------------------
# CLI
# ---------------------------------------------------------------------------

def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    """Parse command-line arguments."""
    parser = argparse.ArgumentParser(
        prog="init_dataset.py",
        description=(
            "Khởi tạo cây thư mục dataset Driver Behavior Monitoring.\n\n"
            "Script này idempotent: chạy lại nhiều lần không ghi đè nội dung\n"
            "đã có (trừ khi dùng --overwrite)."
        ),
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument(
        "--root",
        type=Path,
        default=None,
        help=(
            "Đường dẫn thư mục gốc của dataset. "
            "Mặc định: driver_behavior_dataset_v01/ trong repo root."
        ),
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="In ra các thao tác sẽ thực hiện mà không thực sự tạo file/thư mục.",
    )
    parser.add_argument(
        "--overwrite",
        action="store_true",
        help="Ghi đè các file văn bản đã có (README, .gitignore).",
    )
    parser.add_argument(
        "--verbose",
        action="store_true",
        help="Hiển thị thêm thông tin debug.",
    )
    return parser.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    """Entry point."""
    args = parse_args(argv)
    setup_logging(level=logging.DEBUG if args.verbose else logging.INFO)

    if args.root is not None:
        root = args.root.resolve()
    else:
        paths = DatasetPaths()
        root = paths.dataset_root

    logger.info("Dataset root: %s", root)

    try:
        init_dataset(root=root, dry_run=args.dry_run, overwrite=args.overwrite)
    except Exception as exc:
        logger.error("Initialisation failed: %s", exc, exc_info=True)
        return 1

    return 0


if __name__ == "__main__":
    sys.exit(main())

